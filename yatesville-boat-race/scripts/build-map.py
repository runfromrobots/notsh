"""Build lib/mapData.ts from an OpenStreetMap Overpass JSON export.

Usage: python3 scripts/build-map.py area.json > lib/mapData.ts

The map is rotated 180 degrees: south is at the top (upstream, near
Yatesville Falls) and north is at the bottom (the Mohawk River).
"""
import json
import math
import sys

# Map window (degrees)
LAT_MIN, LAT_MAX = 42.8640, 42.9240
LON_MIN, LON_MAX = -74.4800, -74.4260
WIDTH = 800

LAT_MID = (LAT_MIN + LAT_MAX) / 2
M_PER_LON = 111320 * math.cos(math.radians(LAT_MID))
M_PER_LAT = 110574
SCALE = WIDTH / ((LON_MAX - LON_MIN) * M_PER_LON)
HEIGHT = round((LAT_MAX - LAT_MIN) * M_PER_LAT * SCALE)

CREEK = 175370060
FALLS_INDEX = 199  # end of NY State Preserve Road, at the falls
FINISH_INDEX = 286  # placeholder for The Root, near the mouth
START_HINT_INDEX = 232  # where the "start TBA" marker points; not the real start

FEATURES = {
    "mohawk": [188951605, 188951613, 91009367],
    "lasher": [1389885019, 1389885022, 1389885023],
    "thruway": [4681649, 175370036, 175370038, 175370044, 175370045, 188841852],
    "route5s": [124782281, 172602122, 173555804, 173555805, 1389885020, 1389885021],
    "rail": [97622168, 132181016, 1030420752, 1030420753, 1030420754, 1030420755],
    "anderson": [20117259],
    "preserve": [20120076, 20120078],
}


def project(p):
    x = (LON_MAX - p["lon"]) * M_PER_LON * SCALE
    y = (p["lat"] - LAT_MIN) * M_PER_LAT * SCALE
    return (x, y)


def simplify(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    dmax, idx = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            dmax, idx = d, i
    if dmax > tol:
        return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)
    return [points[0], points[-1]]


def path(points, closed=False):
    out = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in points)
    return out + ("Z" if closed else "")


def main():
    data = json.load(open(sys.argv[1]))
    ways = {e["id"]: e for e in data["elements"] if e["type"] == "way"}

    paths = {}
    for name, ids in FEATURES.items():
        parts = []
        for wid in ids:
            way = ways[wid]
            pts = [project(p) for p in way["geometry"]]
            closed = way.get("tags", {}).get("natural") == "water"
            if closed:
                # A ring starts and ends on the same point, so simplify each half
                mid = len(pts) // 2
                pts = simplify(pts[: mid + 1], 0.6)[:-1] + simplify(pts[mid:], 0.6)
            else:
                pts = simplify(pts, 0.6)
            parts.append(path(pts, closed))
        paths[name] = " ".join(parts)

    creek_pts = [project(p) for p in ways[CREEK]["geometry"]]
    falls = creek_pts[FALLS_INDEX]
    finish = creek_pts[FINISH_INDEX]
    start_hint = creek_pts[START_HINT_INDEX]
    # The race runs from the falls down to The Root.
    race = simplify(creek_pts[FALLS_INDEX : FINISH_INDEX + 1], 0.4)
    # Upstream of the falls the creek is drawn faintly, as context.
    upstream = simplify(creek_pts[: FALLS_INDEX + 1], 0.4)
    downstream = simplify(creek_pts[FINISH_INDEX:], 0.4)

    print("// Generated by scripts/build-map.py from OpenStreetMap data.")
    print("// Map data (c) OpenStreetMap contributors, ODbL.")
    print("// South is up: the creek flows from the top of the map to the bottom.")
    print()
    print(f"export const MAP_WIDTH = {WIDTH}")
    print(f"export const MAP_HEIGHT = {HEIGHT}")
    print()
    print("export const paths = {")
    for name, d in paths.items():
        print(f"  {name}: '{d}',")
    print(f"  creekUpstream: '{path(upstream)}',")
    print(f"  creekRace: '{path(race)}',")
    print(f"  creekDownstream: '{path(downstream)}',")
    print("}")
    print()
    print(f"export const falls = {{ x: {falls[0]:.1f}, y: {falls[1]:.1f} }}")
    print(f"export const startHint = {{ x: {start_hint[0]:.1f}, y: {start_hint[1]:.1f} }}")
    print(f"export const finish = {{ x: {finish[0]:.1f}, y: {finish[1]:.1f} }}")


main()
